using System;
using System.Collections.Generic;
using System.Linq;
using System.Windows;
using System.Windows.Controls;
using MessageBox = System.Windows.MessageBox;

namespace MetroEditor.Windows
{
        /// <summary>
        /// 方向定义编辑器窗口
        /// 功能：新建或修改 DIRECTION_DEFINE 代码块
        /// 支持特性：
        /// - 站点顺序拖拽调整
        /// - 环线/未来线路标记、快车停靠站设置
        /// - 内环/外环方向定义
        /// - 批量添加站点
        /// </summary>
        public partial class EditDirectionWindow : Window
        {
            private readonly List<string> _allStations;       // 全网站点列表
            private readonly HashSet<string> _existingLineIds; // 现有线路ID集合
            private readonly string _editDirectionId;        // 编辑模式下的原方向ID

            // ===== 构造函数重载 =====
            /// <summary>
            /// 新建模式构造函数
            /// </summary>
            public EditDirectionWindow(List<string> stationNames, HashSet<string> existingLineIds)
                : this(stationNames, existingLineIds, null, null, null, null, null, null)
            { Title = "新增方向"; }

            /// <summary>
            /// 完整构造函数（支持编辑模式）
            /// </summary>
            public EditDirectionWindow(
                List<string> stationNames,
                HashSet<string> existingLineIds,
                string? lineId,
                string? dirId,
                List<string>? stations,
                List<string>? attrs,
                string? dirType,
                List<string>? expressStops)
            {
                InitializeComponent();
                _allStations = stationNames ?? new List<string>();
                _existingLineIds = existingLineIds ?? new HashSet<string>();
                _editDirectionId = dirId;

                // 填充线路ID下拉框
                foreach (var id in _existingLineIds.OrderBy(x => x))
                    LineIdComboBox.Items.Add(id);

                // 初始化站点列表（用于左侧待选区）
                RefreshAllStations("");

                // 加载编辑数据（如果是编辑模式）
                if (!string.IsNullOrEmpty(dirId))
                    LoadEditData(lineId, stations, attrs, dirType, expressStops);
                else
                    AutoGenerateDirectionId(); // 新建模式自动生成ID

                // 事件绑定
                LoopCheckBox.Checked += (_, _) => DirectionTypeComboBox.IsEnabled = true;
                LoopCheckBox.Unchecked += (_, _) => DirectionTypeComboBox.IsEnabled = false;
                SearchTextBox.KeyDown += SearchTextBox_KeyDown; // 支持回车快速添加

                Title = "修改方向";
                Loaded += (o, e) => Topmost = false;
            }

            /// <summary>
            /// 加载编辑数据到表单
            /// </summary>
            private void LoadEditData(string? lineId, List<string>? stations, List<string>? attrs, string? dirType, List<string>? expressStops)
            {
                DirectionIdTextBox.Text = _editDirectionId;
                if (!string.IsNullOrEmpty(lineId))
                    LineIdComboBox.Text = lineId;

                // 加载站点序列
                if (stations != null)
                    foreach (var st in stations)
                        SelectedStationListBox.Items.Add(st);

                // 加载属性标记
                if (attrs != null)
                {
                    LoopCheckBox.IsChecked = attrs.Contains("LOOP");
                    FutureCheckBox.IsChecked = attrs.Contains("FUTURE");

                    // 环线方向类型
                    if (attrs.Contains("INNER"))
                        DirectionTypeComboBox.SelectedIndex = 0;
                    else if (attrs.Contains("OUTER"))
                        DirectionTypeComboBox.SelectedIndex = 1;
                }

                // 加载快车停靠站
                if (expressStops != null && expressStops.Count > 0)
                    ExpressStopsTextBox.Text = string.Join(", ", expressStops);

                // 设置方向类型下拉框状态
                if (!string.IsNullOrEmpty(dirType))
                {
                    DirectionTypeComboBox.IsEnabled = true;
                    DirectionTypeComboBox.SelectedIndex = dirType.ToLowerInvariant() == "inner" ? 0 : 1;
                }
            }

        /// <summary>
        /// 自动生成方向ID（简单规则：D + 数字）
        /// </summary>
        private void AutoGenerateDirectionId()
        {
            DirectionIdTextBox.Text = "D" + (_allStations.Count > 0 ? _allStations.Count.ToString() : "1");
        }

        // ==================== 站点列表操作 ====================
        /// <summary>
        /// 刷新左侧所有站点列表（支持搜索过滤）
        /// </summary>
        private void RefreshAllStations(string filter)
        {
            var list = string.IsNullOrEmpty(filter)
                ? _allStations
                : _allStations.Where(s => s.Contains(filter, StringComparison.OrdinalIgnoreCase)).ToList();
            AllStationListBox.ItemsSource = list;
        }

        private void SearchTextBox_TextChanged(object sender, TextChangedEventArgs e)
            => RefreshAllStations(SearchTextBox.Text);

        /// <summary>
        /// 添加选中站点到右侧列表
        /// </summary>
        private void AddSelected_Click(object sender, RoutedEventArgs e)
        {
            var selected = AllStationListBox.SelectedItems.Cast<string>().ToList();
            foreach (var item in selected)
                if (!SelectedStationListBox.Items.Contains(item))
                    SelectedStationListBox.Items.Add(item);
        }

        /// <summary>
        /// 从右侧列表移除选中站点
        /// </summary>
        private void RemoveSelected_Click(object sender, RoutedEventArgs e)
        {
            var selected = SelectedStationListBox.SelectedItems.Cast<string>().ToList();
            foreach (var item in selected)
                SelectedStationListBox.Items.Remove(item);
        }

        /// <summary>
        /// 上移选中站点
        /// </summary>
        private void MoveUp_Click(object sender, RoutedEventArgs e)
        {
            int idx = SelectedStationListBox.SelectedIndex;
            if (idx > 0)
            {
                var item = SelectedStationListBox.Items[idx];
                SelectedStationListBox.Items.RemoveAt(idx);
                SelectedStationListBox.Items.Insert(idx - 1, item);
                SelectedStationListBox.SelectedIndex = idx - 1;
            }
        }

        /// <summary>
        /// 下移选中站点
        /// </summary>
        private void MoveDown_Click(object sender, RoutedEventArgs e)
        {
            int idx = SelectedStationListBox.SelectedIndex;
            if (idx >= 0 && idx < SelectedStationListBox.Items.Count - 1)
            {
                var item = SelectedStationListBox.Items[idx];
                SelectedStationListBox.Items.RemoveAt(idx);
                SelectedStationListBox.Items.Insert(idx + 1, item);
                SelectedStationListBox.SelectedIndex = idx + 1;
            }
        }

        /// <summary>
        /// 搜索框回车键快速添加站点
        /// </summary>
        private void SearchTextBox_KeyDown(object sender, System.Windows.Input.KeyEventArgs e)
        {
            if (e.Key == System.Windows.Input.Key.Enter)
            {
                string input = SearchTextBox.Text.Trim();
                if (string.IsNullOrEmpty(input)) return;

                if (!SelectedStationListBox.Items.Contains(input))
                {
                    SelectedStationListBox.Items.Add(input);
                    SearchTextBox.Text = ""; // 清空输入，方便继续添加
                }
                else
                {
                    MessageBox.Show($"站点 '{input}' 已添加", "提示",
                        MessageBoxButton.OK, MessageBoxImage.Information);
                }
                e.Handled = true;
            }
        }

        /// <summary>
        /// 批量添加站点（多行文本输入）
        /// </summary>
        private void BatchAdd_Click(object sender, RoutedEventArgs e)
        {
            var dialog = new InputDialog(
                "请输入站点名称，每行一个：",
                "批量添加站点",
                "",
                this.Owner ?? this
            );
            if (dialog.ShowDialog() == true)
            {
                string input = dialog.InputText;
                if (string.IsNullOrWhiteSpace(input)) return;

                // 按行分割处理
                var lines = input.Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries)
                                 .Select(s => s.Trim())
                                 .Where(s => !string.IsNullOrEmpty(s))
                                 .ToList();

                if (lines.Count == 0) return;

                int added = 0, notFound = 0;
                foreach (var line in lines)
                {
                    if (!SelectedStationListBox.Items.Contains(line))
                    {
                        SelectedStationListBox.Items.Add(line);
                        SearchTextBox.Text = ""; // 清空输入，方便继续添加
                    }
                    else
                    {
                        MessageBox.Show($"站点 '{line}' 已添加", "提示",
                            MessageBoxButton.OK, MessageBoxImage.Information);
                    }
                }

                // 显示结果反馈
                string msg = $"成功添加 {added} 个站点";
                if (notFound > 0)
                    msg += $"，{notFound} 个站点未找到（请检查名称）";
                MessageBox.Show(msg, "批量添加完成",
                    MessageBoxButton.OK, MessageBoxImage.Information);
            }
        }

        // ==================== 代码生成 ====================
        /// <summary>
        /// 生成 DIRECTION_DEFINE 代码块
        /// </summary>
        /// <returns>生成的代码字符串，验证失败返回null</returns>
        private string? GenerateCode()
        {
            string lid = LineIdComboBox.Text.Trim();
            string did = DirectionIdTextBox.Text.Trim();
            var selected = SelectedStationListBox.Items.Cast<string>().ToList();

            // 基础验证
            if (string.IsNullOrEmpty(lid) || string.IsNullOrEmpty(did) || selected.Count < 2)
                return null;

            var attrs = new List<string>();

            if (LoopCheckBox.IsChecked == true) attrs.Add("LOOP");
            if (FutureCheckBox.IsChecked == true) attrs.Add("FUTURE");

            // 解析快车停靠站（逗号分隔）
            var expressStops = ExpressStopsTextBox.Text
                .Split(new[] { ',', '，', ';', '；' }, StringSplitOptions.RemoveEmptyEntries)
                .Select(s => s.Trim())
                .Where(s => s.Length > 0)
                .Distinct()
                .ToList();

            string dirType = "";
            if (LoopCheckBox.IsChecked == true)
            {
                var selectedType = (DirectionTypeComboBox.SelectedItem as ComboBoxItem)?.Content?.ToString();
                if (selectedType == "内环") dirType = "INNER";
                else if (selectedType == "外环") dirType = "OUTER";
            }

            var lines = new List<string>
            {
                $"DIRECTION_DEFINE {did} {lid}",
                $"    STATIONS [{string.Join(", ", selected.Select(s => $"'{s}'"))}]"
            };

            // 添加属性标记
            if (attrs.Contains("LOOP"))
            {
                string loopLine = "    LOOP";
                if (!string.IsNullOrEmpty(dirType)) loopLine += $" {dirType}";
                lines.Add(loopLine);
            }
            if (attrs.Contains("FUTURE")) lines.Add("    FUTURE");
            if (expressStops.Count > 0)
                lines.Add($"    EXPRESS_STOPS [{string.Join(", ", expressStops.Select(s => $"'{s}'"))}]");
            lines.Add("    DISTANCE AUTO");

            // 注意：DISTANCE AUTO 未添加，用户可手动补充
            lines.Add("END_DEFINE");

            return string.Join("\n", lines);
        }

        // ==================== 事件处理 ====================
        private void GeneratePreview_Click(object sender, RoutedEventArgs e)
        {
            string? code = GenerateCode();
            if (code == null)
            {
                MessageBox.Show("请确保线路ID、方向ID已填，且至少选择两个站点", "提示", MessageBoxButton.OK, MessageBoxImage.Error);
                return;
            }
            PreviewTextBox.Text = code;
        }

        private void Copy_Click(object sender, RoutedEventArgs e)
        {
            if (string.IsNullOrEmpty(PreviewTextBox.Text))
            {
                MessageBox.Show("没有代码可复制，请先生成预览", "提示", MessageBoxButton.OK, MessageBoxImage.Information);
                return;
            }
            try
            {
                MainWindow.InsertText(PreviewTextBox.Text);
                MessageBox.Show("代码已复制到主界面", "成功", MessageBoxButton.OK, MessageBoxImage.Information);
                Close();
            }
            catch (Exception ex)
            {
                MessageBox.Show($"复制失败：{ex.Message}", "错误", MessageBoxButton.OK, MessageBoxImage.Error);
            }
        }

        private void Cancel_Click(object sender, RoutedEventArgs e) => Close();
    }
}